CREATE INDEX IF NOT EXISTS idx_word_clean_pep_difficulty ON public.word_clean(pep_difficulty);
CREATE INDEX IF NOT EXISTS idx_word_clean_source_difficulty ON public.word_clean(source_difficulty);

