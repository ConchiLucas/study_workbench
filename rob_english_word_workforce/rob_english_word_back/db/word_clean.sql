ranked AS (
    SELECT
        btrim(w.word) AS word,
        w.meaning,
        COALESCE(w.difficulty, 50) AS difficulty,
        COALESCE(w.frequency, 50) AS frequency,
        COALESCE(w.sentence, '') AS sentence,
        row_number() OVER (
            PARTITION BY lower(btrim(w.word))
            ORDER BY pl.pep_difficulty NULLS LAST, w.id
        ) AS row_number
    FROM public.word w
    LEFT JOIN public.word_library wl ON wl.id = w.library_id
    LEFT JOIN pep_levels pl ON pl.library_name = wl.library_name
    WHERE w.word IS NOT NULL
      AND btrim(w.word) <> ''
      AND btrim(w.word) !~ '\s'
)
INSERT INTO public.word_clean (word, meaning, difficulty, frequency, sentence)
SELECT
    ranked.word,
    ranked.meaning,
    ranked.difficulty,
    ranked.frequency,
    ranked.sentence
FROM ranked
WHERE ranked.row_number = 1
ORDER BY lower(ranked.word);

