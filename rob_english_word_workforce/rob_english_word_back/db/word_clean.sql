-- Create a deduplicated single-word table derived from public.word.
-- Keeps only: id, word, meaning, difficulty, frequency, sentence.
-- Excludes phrases where word contains whitespace.
-- When a word appears in multiple PEP textbook levels, keeps the lowest PEP level as its source.

CREATE TABLE IF NOT EXISTS public.word_clean (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word varchar(100) NOT NULL,
    meaning varchar(200) NOT NULL,
    difficulty int2 DEFAULT 50 NOT NULL,
    frequency int2 DEFAULT 50 NOT NULL,
    sentence varchar(800) DEFAULT ''::character varying NULL,
    pep_difficulty int2 NULL,
    pep_difficulty_label varchar(200) NULL,
    source_difficulty int2 NULL,
    source_difficulty_label varchar(200) NULL
);

COMMENT ON TABLE public.word_clean IS '去重后的单词表，不包含词组';
COMMENT ON COLUMN public.word_clean.id IS 'id';
COMMENT ON COLUMN public.word_clean.word IS '英文单词';
COMMENT ON COLUMN public.word_clean.meaning IS '中文含义';
COMMENT ON COLUMN public.word_clean.difficulty IS '难度分';
COMMENT ON COLUMN public.word_clean.frequency IS '使用频率';
COMMENT ON COLUMN public.word_clean.sentence IS '例句';
COMMENT ON COLUMN public.word_clean.pep_difficulty IS '人教版教材难度等级，数字越小越基础';
COMMENT ON COLUMN public.word_clean.pep_difficulty_label IS '人教版教材难度标签';
COMMENT ON COLUMN public.word_clean.source_difficulty IS '统一来源难度等级，数字越小越基础，包含人教版、四六级、考研、专四专八、雅思托福、SAT、GRE 等';
COMMENT ON COLUMN public.word_clean.source_difficulty_label IS '统一来源难度标签';

ALTER TABLE public.word_clean
    ADD COLUMN IF NOT EXISTS pep_difficulty int2 NULL;

ALTER TABLE public.word_clean
    ADD COLUMN IF NOT EXISTS pep_difficulty_label varchar(200) NULL;

ALTER TABLE public.word_clean
    ADD COLUMN IF NOT EXISTS source_difficulty int2 NULL;

ALTER TABLE public.word_clean
    ADD COLUMN IF NOT EXISTS source_difficulty_label varchar(200) NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uk_word_clean_word_lower ON public.word_clean (lower(word));
