-- One current TTS asset per public.word_clean base word.
-- The external task center owns generation and updates; this project initializes and reads the rows.

CREATE TABLE IF NOT EXISTS public.word_clean_tts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word_clean_id bigint NOT NULL,
    word varchar(100) NOT NULL,
    status varchar(32) NOT NULL DEFAULT 'pending',
    provider varchar(64) NOT NULL DEFAULT '',
    model varchar(128) NOT NULL DEFAULT '',
    voice varchar(128) NOT NULL DEFAULT '',
    audio_format varchar(32) NOT NULL DEFAULT '',
    tts_bucket varchar(128) NOT NULL DEFAULT '',
    tts_object_key text NOT NULL DEFAULT '',
    tts_object_url text NOT NULL DEFAULT '',
    content_type varchar(128) NOT NULL DEFAULT '',
    file_size bigint NULL,
    duration_ms integer NULL,
    generated_at timestamptz NULL,
    error_message text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_word_clean_tts_word_clean
        FOREIGN KEY (word_clean_id) REFERENCES public.word_clean(id) ON DELETE CASCADE
);

COMMENT ON TABLE public.word_clean_tts IS 'word_clean 基础单词的一对一 TTS 音频记录';
COMMENT ON COLUMN public.word_clean_tts.id IS '主键';
COMMENT ON COLUMN public.word_clean_tts.word_clean_id IS 'word_clean.id，一词一条 TTS 记录';
COMMENT ON COLUMN public.word_clean_tts.word IS '生成时使用的基础单词快照';
COMMENT ON COLUMN public.word_clean_tts.status IS '任务中心维护的状态：pending/running/success/failed';
COMMENT ON COLUMN public.word_clean_tts.provider IS 'TTS 服务商';
COMMENT ON COLUMN public.word_clean_tts.model IS 'TTS 模型';
COMMENT ON COLUMN public.word_clean_tts.voice IS 'TTS 音色';
COMMENT ON COLUMN public.word_clean_tts.audio_format IS '音频格式';
COMMENT ON COLUMN public.word_clean_tts.tts_bucket IS 'MinIO bucket';
COMMENT ON COLUMN public.word_clean_tts.tts_object_key IS 'MinIO object key';
COMMENT ON COLUMN public.word_clean_tts.tts_object_url IS '前端可访问的 MinIO 代理 URL';
COMMENT ON COLUMN public.word_clean_tts.content_type IS '音频 Content-Type';
COMMENT ON COLUMN public.word_clean_tts.file_size IS '音频字节数';
COMMENT ON COLUMN public.word_clean_tts.duration_ms IS '音频时长（毫秒）';
COMMENT ON COLUMN public.word_clean_tts.generated_at IS '成功生成时间';
COMMENT ON COLUMN public.word_clean_tts.error_message IS '任务中心回填的最近一次错误';
COMMENT ON COLUMN public.word_clean_tts.created_at IS '创建时间';
COMMENT ON COLUMN public.word_clean_tts.updated_at IS '更新时间';

CREATE UNIQUE INDEX IF NOT EXISTS uk_word_clean_tts_word_clean
    ON public.word_clean_tts(word_clean_id);

CREATE UNIQUE INDEX IF NOT EXISTS uk_word_clean_tts_word
    ON public.word_clean_tts(word);

CREATE INDEX IF NOT EXISTS idx_word_clean_tts_status
    ON public.word_clean_tts(status);

INSERT INTO public.word_clean_tts (word_clean_id, word, status)
SELECT wc.id, wc.word, 'pending'
FROM public.word_clean wc
ON CONFLICT (word_clean_id) DO NOTHING;
